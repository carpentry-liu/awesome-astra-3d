const evidenceNames: Record<EvidenceLevel, string> = {
  official: 'Official showcase',
  author: 'Creator statement',
  secondary: 'Secondary evidence',
  reference: 'Method reference',
};
export function categoryLabel(category: string, locale: Locale): string {
  return locale === 'en' ? (categoryNames[category] ?? category) : category;
}
export function evidenceLabel(level: EvidenceLevel, locale: Locale): string {
  const zh = {
    official: '官方展示',
    author: '作者自述',
    secondary: '转引待复核',
    reference: '方法参考',
  };
  return locale === 'en' ? evidenceNames[level] : zh[level];
}
export function workTitle(
  item: Pick<CaseIndex, 'title' | 'titleEn'>,
  locale: Locale,
): string {
  return locale === 'en' && item.titleEn ? item.titleEn : item.title;
}
